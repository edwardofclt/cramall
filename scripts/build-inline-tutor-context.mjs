import { writeFileSync } from 'node:fs';
import { createServer } from 'vite';
import { createServer as createHttpServer } from 'node:http';

// Attach Vite's HMR transport to an unlistened server: generation needs no ports.
const offlineServer = createHttpServer();
const server = await createServer({ configFile: false, server: { middlewareMode: true, watch: null, hmr: {server:offlineServer} }, appType: 'custom' });
try {
  const { SUBJECTS } = await server.ssrLoadModule('/src/content/subjects.ts');
  const { projectInlineLessons } = await server.ssrLoadModule('/src/tutor/lesson-projection.ts');
  const lessons = projectInlineLessons(SUBJECTS);
  writeFileSync('src/tutor/inline-manifest.mjs', `// Generated by scripts/build-inline-tutor-context.mjs. No assessment data.\nexport const inlineLessons = ${JSON.stringify(lessons, null, 2)};\n`);
} finally { await server.close(); }

import { writeFileSync } from 'node:fs';
import { createServer } from 'vite';
import { createServer as createHttpServer } from 'node:http';

// Attach Vite's HMR transport to an unlistened server: generation needs no ports.
const offlineServer = createHttpServer();
const server = await createServer({ configFile: false, server: { middlewareMode: true, watch: null, hmr: {server:offlineServer} }, appType: 'custom' });
try {
  const math = (await server.ssrLoadModule('/src/content/math/u01.ts')).unit01Lessons[0];
  const reading = (await server.ssrLoadModule('/src/content/reading/u04.ts')).unit04Lessons[0];
  const lessons = [math, reading].map(lesson => {
    const isReading = lesson.id.startsWith('reading-');
    const source = isReading ? lesson.learnCards.find(card => card.widget?.type === 'theme-evidence-collector').widget.config.source : null;
    return {
      id: lesson.id, title: lesson.title, subject: isReading ? 'Reading' : 'Math',
      guide: isReading ? { id: 'winnie', name: 'Winnie' } : { id: 'nutty', name: 'Nutty' }, source,
      stages: [
        { key: 'intro', title: 'Meet the big idea', text: lesson.intro.map(line => line.text) },
        ...lesson.learnCards.map(card => {
          const stage = { key: `card:${card.id}`, title: card.title, text: card.blocks.map(block => block.text) };
          if (card.widget?.type === 'place-value-builder') stage.activity = { type: card.widget.type, target: card.widget.config.target, columns: card.widget.config.periods === 3 ? 9 : 6 };
          if (card.widget?.type === 'theme-evidence-collector') stage.activity = { type: card.widget.type, themeChoices: card.widget.config.themeChoices, evidence: card.widget.config.evidence.map(item => ({ id: item.id, quote: item.sourceQuote })) };
          return stage;
        }),
        { key: 'worked', title: lesson.workedExample.title, text: lesson.workedExample.steps, ...(lesson.workedExample.passage ? { source: lesson.workedExample.passage } : {}) },
        { key: 'outro', title: 'Reflect on what you learned', text: ['Summarize the main idea and one strategy from this lesson. Invite the learner to explain it in their own words. The scored Quick Check is separate.'] },
      ],
    };
  });
  writeFileSync('src/tutor/inline-manifest.mjs', `// Generated by scripts/build-inline-tutor-context.mjs. No assessment data.\nexport const inlineLessons = ${JSON.stringify(lessons, null, 2)};\n`);
} finally { await server.close(); }
